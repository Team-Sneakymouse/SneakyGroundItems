package com.danidipp.sneakygrounditems.integration.magicspells

import com.danidipp.sneakygrounditems.command.Command
import com.danidipp.sneakygrounditems.commerce.Currency
import com.nisovin.magicspells.MagicSpells
import io.papermc.paper.dialog.Dialog
import io.papermc.paper.registry.data.dialog.ActionButton
import io.papermc.paper.registry.data.dialog.DialogBase
import io.papermc.paper.registry.data.dialog.action.DialogAction
import io.papermc.paper.registry.data.dialog.body.DialogBody
import io.papermc.paper.registry.data.dialog.input.DialogInput
import io.papermc.paper.registry.data.dialog.type.DialogType
import net.kyori.adventure.text.Component
import net.kyori.adventure.text.event.ClickCallback
import net.kyori.adventure.text.format.NamedTextColor
import org.bukkit.Bukkit
import org.bukkit.SoundCategory
import org.bukkit.entity.Player

/**
 * The Price Gun menu's "type an exact price" dialog. The Price Gun itself lives in MagicSpells
 * (spells-item-pricegun-menu.yml, generated by the workspace's pricegun/build_pricegun.py); its price is the
 * player variable pricegun<Currency>, and each currency has its own menu spell, reopened after the dialog.
 */
internal object PriceGunDialog {
    val currencies = listOf(Currency.GOLD, Currency.SILVER, Currency.PENNY)

    fun variableName(currency: Currency) = "pricegun$currency"

    fun menuSpell(currency: Currency) = "item-pricegun-menu-${currency.id}"

    /** Digits only, ignoring spaces, commas, dots and underscores used as separators; capped at the sell limit. */
    fun parsePrice(raw: String): Int? {
        val digits = raw.trim().filterNot { it == ' ' || it == ',' || it == '.' || it == '_' }
        if (digits.isEmpty() || !digits.all(Char::isDigit)) return null
        return digits.trimStart('0').ifEmpty { "0" }
            .let { if (it.length > 10) Command.MAX_SELL_PRICE.toLong() else it.toLong() }
            .coerceAtMost(Command.MAX_SELL_PRICE.toLong())
            .toInt()
    }

    fun show(player: Player, currency: Currency, error: Component? = null) {
        val variables = MagicSpells.getVariableManager()
        val current = variables?.getValue(variableName(currency), player)?.toLong()?.coerceAtLeast(0) ?: 0
        val body = buildList {
            add(DialogBody.plainMessage(Component.text("Type the $currency price for your next shot.")))
            if (error != null) add(DialogBody.plainMessage(error))
        }
        val confirm = ActionButton.create(
            Component.text("Set price", NamedTextColor.GREEN), Component.text("Use this $currency price"), 100,
            DialogAction.customClick({ response, audience ->
                val who = audience as? Player ?: return@customClick
                val price = parsePrice(response.getText("price").orEmpty())
                if (price == null) {
                    show(who, currency, Component.text("That isn't a whole number. Try again.", NamedTextColor.RED))
                    return@customClick
                }
                MagicSpells.getVariableManager()?.set(variableName(currency), who, price.toDouble())
                who.playSound(who.location, "lom:sfx.pricegun", SoundCategory.MASTER, 0.5f, 1.0f)
                reopenMenu(who, currency)
            }, ClickCallback.Options.builder().uses(1).build()),
        )
        val cancel = ActionButton.create(
            Component.text("Cancel"), null, 100,
            DialogAction.customClick({ _, audience ->
                (audience as? Player)?.let { reopenMenu(it, currency) }
            }, ClickCallback.Options.builder().uses(1).build()),
        )
        val dialog = Dialog.create { factory ->
            factory.empty()
                .base(
                    DialogBase.builder(Component.text("Set $currency price", NamedTextColor.GOLD))
                        .canCloseWithEscape(true)
                        .body(body)
                        .inputs(
                            listOf(
                                DialogInput.text("price", Component.text("Price ($currency)"))
                                    .initial(current.toString())
                                    .maxLength(13)
                                    .build(),
                            ),
                        )
                        .build(),
                )
                .type(DialogType.confirmation(confirm, cancel))
        }
        player.showDialog(dialog)
    }

    private fun reopenMenu(player: Player, currency: Currency) {
        Bukkit.dispatchCommand(Bukkit.getConsoleSender(), "ms cast as ${player.name} ${menuSpell(currency)}")
    }
}
